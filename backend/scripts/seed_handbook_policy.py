def seed_handbook_documents(db: Session, *, replace: bool = True) -> int:
    """편람 조항을 policy_documents 테이블에 적재한다."""
    if replace:
        deleted = db.execute(
            delete(PolicyDocument).where(
                PolicyDocument.document_code.like(f"{DOCUMENT_CODE_PREFIX}-%"),
                PolicyDocument.policy_version == POLICY_VERSION,
            )
        )
        print(f"[seed] 기존 편람 청크 {deleted.rowcount or 0}건 삭제")

    for clause in HANDBOOK_CLAUSES:
        db.add(
            PolicyDocument(
                document_code=f"{DOCUMENT_CODE_PREFIX}-{clause['seq']}",
                document_name=DOCUMENT_NAME,
                article=clause["article"],
                content=clause["content"],
                policy_version=POLICY_VERSION,
                keywords=f"{clause['keywords']} {clause['content']}".lower(),
                is_active=True,
            )
        )

    db.commit()
    return len(HANDBOOK_CLAUSES)


def main() -> None:
    db = SessionLocal()
    try:
        inserted = seed_handbook_documents(db)
        total = len(
            db.scalars(
                select(PolicyDocument.document_id).where(
                    PolicyDocument.document_code.like(f"{DOCUMENT_CODE_PREFIX}-%")
                )
            ).all()
        )
        print(f"[seed] 편람 조항 {inserted}건 적재 완료 (DB 총 {total}건)")
    finally:
        db.close()


if __name__ == "__main__":
    main()